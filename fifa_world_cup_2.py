# Import Libraries
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
df=pd.read_csv('/content/drive/MyDrive/Data Analyst/Python/Pandas/fifa_world_cup_2026_player_performance.csv')
df

# DATA EXPLORATION
# ==========================================

print("Shape of Dataset:", df.shape)

print("Missing Values:")
df.isnull().sum()

print("Dataset Information:")
df.info()

print("Statistical Summary:")
df.describe()

# Remove duplicates if any
df.drop_duplicates(inplace=True)

# INSIGHT 1
# Average Player Rating by Position
# ==========================================

position_rating = df.groupby('position')['player_rating'].mean().sort_values(ascending=False)
print(position_rating)

plt.figure(figsize=(8,5))
sns.barplot(x=position_rating.index,
            y=position_rating.values)

plt.title("Insight 1: Average Player Rating by Position")
plt.xlabel("Position")
plt.ylabel("Average Rating")
plt.show()

print("Insight 1:")
print("Midfielders have the highest average rating.")

# INSIGHT 2
# Goals vs Player Rating
# ==========================================

goal_rating_corr = np.corrcoef(
    df['goals'],
    df['player_rating'])[0,1]

print("Correlation Between Goals and Rating:")
print(goal_rating_corr)

plt.figure(figsize=(8,5))
sns.scatterplot(data=df,
                x='goals',
                y='player_rating')

plt.title("Insight 2: Goals vs Player Rating")
plt.show()

print("Players scoring more goals generally receive higher ratings.")

# ==========================================
# INSIGHT 3
# Performance Score vs Rating
# ==========================================

performance_corr = np.corrcoef(
    df['performance_score'],
    df['player_rating'])[0,1]

print("Correlation Between Performance Score and Rating:")
print(performance_corr)

plt.figure(figsize=(8,5))
sns.regplot(data=df,
            x='performance_score',
            y='player_rating')

plt.title("Performance Score vs Player Rating")
plt.show()

print("Performance score strongly influences player ratings.")

# ==========================================
# INSIGHT 4
# Distance Covered by Position
# ==========================================

distance = df.groupby('position')['distance_covered_km'].mean()

plt.figure(figsize=(8,5))
sns.barplot(x=distance.index,
            y=distance.values)

plt.title("Insight 4: Average Distance Covered by Position")
plt.xlabel("Position")
plt.ylabel("Distance Covered (km)")
plt.show()

print("Midfielders cover the most distance on average.")

# ==========================================
# INSIGHT 5
# Top 10 Goal Scoring Teams
# ==========================================

team_goals = (
    df.groupby('team')['goals']
      .sum()
      .sort_values(ascending=False)
      .head(10)
)

plt.figure(figsize=(10,6))
sns.barplot(
    x=team_goals.values,
    y=team_goals.index
)

plt.title("Insight 5: Top 10 Goal Scoring Teams")
plt.xlabel("Goals")
plt.ylabel("Team")
plt.show()

print("Top teams dominate tournament scoring.")

# ==========================================
# INSIGHT 7
# Age vs Player Rating
# ==========================================

age_rating = df.groupby('age')['player_rating'].mean()

plt.figure(figsize=(10,5))
sns.lineplot(
    x=age_rating.index,
    y=age_rating.values
)

plt.title("Insight 7: Age vs Average Player Rating")
plt.xlabel("Age")
plt.ylabel("Average Rating")
plt.show()

print("Player performance peaks around prime playing age.")

# ==========================================
# INSIGHT 8
# Top Goal Contributors
# ==========================================

df['goal_contribution'] = (
    df['goals'] +
    df['assists']
)

top_players = (
    df.groupby('player_name')['goal_contribution']
      .sum()
      .sort_values(ascending=False)
      .head(10)
)

plt.figure(figsize=(10,6))
sns.barplot(
    x=top_players.values,
    y=top_players.index
)

plt.title("Insight 8: Top 10 Players by Goal Contribution")
plt.xlabel("Goals + Assists")
plt.ylabel("Player")
plt.show()

print("These players contribute most through goals and assists.")